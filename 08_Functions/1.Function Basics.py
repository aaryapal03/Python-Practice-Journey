
# Simple Function
def greet():
    print("Hello, Welcome to Python!")

greet()

# Function with Parameters
def student(name):
    print("Student Name:", name)

student("Aarya")


# Function with Multiple Parameters
def introduction(name, age, course):
    print("Name :", name)
    print("Age :", age)
    print("Course :", course)

introduction("Aarya", 19, "Data Science")


# Function Returning a Value
def add(a, b):
    return a + b

result = add(10, 20)
print("Sum =", result)


# Function Without Return Value
def message():
    print("Learning Python Functions!")


message()

# Calling a Function Multiple Times

def welcome():
    print("Welcome!")


welcome()
welcome()
welcome()

