
# Original List
numbers = [10, 20, 30, 40, 50]
print("Original List:")
print(numbers)

print()


# append()
numbers.append(60)
print("append()")
print(numbers)

print()


# insert()
numbers.insert(2, 25)
print("insert()")
print(numbers)

print()


# extend()
numbers.extend([70, 80])
print("extend()")
print(numbers)

print()


# remove()
numbers.remove(40)
print("remove()")
print(numbers)

print()


# pop()
numbers.pop()
print("pop()")
print(numbers)

print()


# index()
print("index()")
print(numbers.index(30))

print()

# count()
numbers.append(20)
print("count()")
print(numbers.count(20))

print()


# sort()
numbers.sort()
print("sort()")
print(numbers)

print()


# reverse()
numbers.reverse()
print("reverse()")
print(numbers)

print()


# copy()
new_list = numbers.copy()
print(new_list)

print()


# clear()
sample = [1, 2, 3]
sample.clear()
print(sample)

print()


# Built-in Functions
values = [15, 5, 30, 20, 10]
print("Built-in Functions")

print("Length :", len(values))
print("Minimum :", min(values))
print("Maximum :", max(values))
print("Sum :", sum(values))
print("Sorted :", sorted(values))

print()


