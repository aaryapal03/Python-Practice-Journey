
# Import the math module
import math

# sqrt()
print(math.sqrt(25))
print()

# pow()
print(math.pow(2, 5))
print()

# ceil()
print(math.ceil(4.2))
print(math.ceil(7.9))
print()

# floor()
print(math.floor(4.8))
print(math.floor(7.1))
print()

# factorial()
print(math.factorial(5))
print()

# fabs()
print(math.fabs(-25))
print()

# gcd()
print(math.gcd(24, 36))
print()

# lcm()
print(math.lcm(12, 18))
print()

# trunc()
print(math.trunc(9.87))
print()

# Constants
print("Mathematical Constants")
print("Value of pi :", math.pi)
print("Value of e :", math.e)
print("Value of tau :", math.tau)

print()

# Trigonometric Functions
print("Trigonometric Functions")
print("sin(90°) =", math.sin(math.radians(90)))
print("cos(0°) =", math.cos(math.radians(0)))
print("tan(45°) =", math.tan(math.radians(45)))

print()

# Logarithmic Functions

print("Logarithmic Functions")
print("log10(100) =", math.log10(100))
print("log2(16) =", math.log2(16))
print("Natural Log of 10 =", math.log(10))

print()

#End of Program
