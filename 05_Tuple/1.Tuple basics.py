
# Creating a Tuple
fruits = ("Apple", "Banana", "Mango", "Orange")
print(fruits)

print()

# Creating a Tuple of Numbers

numbers = (10, 20, 30, 40, 50)
print(numbers)

print()

# Creating a Mixed Tuple

mixed_tuple = ("Aarya", 19, 89.5, True)
print(mixed_tuple)

print()

# Empty Tuple

empty_tuple = ()
print(empty_tuple)

print()

# Single Element Tuple
# (Comma is mandatory)

single_tuple = (100,)
print(single_tuple)

print()

# Accessing Elements

print("First Fruit :", fruits[0])
print("Second Fruit:", fruits[1])
print("Last Fruit  :", fruits[-1])

print()


# Type of Tuple
print("Type:", type(fruits))

print()

