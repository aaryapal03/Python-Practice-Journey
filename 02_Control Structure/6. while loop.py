
# Example 1 : Print Numbers from 1 to 5
print("Numbers from 1 to 5:")

count = 1

while count <= 5:
    print(count)
    count += 1

print()


# Example 2 : Print Even Numbers from 2 to 10
print("Even Numbers:")

number = 2

while number <= 10:
    print(number)
    number += 2

print()


# Example 3 : Countdown
print("Countdown:")

count = 5

while count >= 1:
    print(count)
    count -= 1

print("Blast Off!")

print()


# Example 4 : Sum of Numbers from 1 to 10
total = 0
num = 1

while num <= 10:
    total += num
    num += 1

print("Sum =", total)

print()


