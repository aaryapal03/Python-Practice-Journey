
# Arithmetic Operators
a = 10
b = 3

print("Arithmetic Operators")
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor Division:", a // b)
print("Modulus:", a % b)
print("Exponent:", a ** b)

print()


# Comparison Operators
print("Comparison Operators")
print("a == b :", a == b)
print("a != b :", a != b)
print("a > b  :", a > b)
print("a < b  :", a < b)
print("a >= b :", a >= b)
print("a <= b :", a <= b)

print()


# Assignment Operators
x = 5
print("Assignment Operators")
print("Initial Value:", x)

x += 3
print("After += :", x)

x -= 2
print("After -= :", x)

x *= 4
print("After *= :", x)

x //= 2
print("After //= :", x)

print()


# Logical Operators
p ="Rahul"
