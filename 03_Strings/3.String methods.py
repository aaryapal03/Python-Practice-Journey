
# Original String
text = "python programming"
print("Original String :", text)

print()


# Capitalize
print("capitalize()")
print(text.capitalize())

print()


# Upper Case
print("upper()")
print(text.upper())

print()


# Lower Case
print("lower()")
print(text.lower())

print()


# Title Case
print("title()")
print(text.title())

print()


# Swap Case
print("swapcase()")
print(text.swapcase())

print()


# Replace
print("replace()")
print(text.replace("python", "Java"))

print()


# Find
print("find()")
print(text.find("programming"))

print()


# Count
print("count()")
print(text.count("m"))

print()


# Startswith
print("startswith()")
print(text.startswith("python"))

print()


# Endswith
print("endswith()")
print(text.endswith("programming"))

print()


# Split
print("split()")
print(text.split())

print()


# Join
print("join()")
words = ["Python", "AI", "Data Science"]
print(" - ".join(words))

print()


# Strip
text2 = "   Hello Python   "

print("strip()")
print(text2.strip())

print()


# Lstrip
print("lstrip()")
print(text2.lstrip())

print()


# Rstrip
print("rstrip()")
print(text2.rstrip())

print()


# Isalpha
print("isalpha()")
print("Python".isalpha())

print()


# Isdigit
print("isdigit()")
print("12345".isdigit())

print()


# Isalnum
print("isalnum()")
print("Python123".isalnum())

print()


# Islower
print("islower()")
print(text.islower())

print()


# Isupper
print("isupper()")
print(text.upper().isupper())

print()


