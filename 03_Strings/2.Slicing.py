
# Creating a String
text = "Python Programming"
print("Original String:", text)

print()


# Slicing from Start Index
print("text[0:6]  :", text[0:6])

print()


# Slicing from Middle
print("text[7:18] :", text[7:18])

print()


# Slicing from Beginning
print("text[:6]   :", text[:6])

print()


# Slicing Till End
print("text[7:]   :", text[7:])

print()


# Negative Slicing
print("text[-11:] :", text[-11:])
print("text[:-12] :", text[:-12])

print()


# Slicing with Step value
print("text[::2]  :", text[::2])
print("text[::3]  :", text[::3])

print()


# Reverse a String
print("Reverse String :", text[::-1])


