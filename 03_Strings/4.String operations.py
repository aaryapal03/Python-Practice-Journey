
# String Concatenation (+)
first_name = "Aarya"
last_name = "Pal"

full_name = first_name + " " + last_name

print("Concatenation:")
print(full_name)

print()


# String Repetition (*)
text = "Python "

print("Repetition:")
print(text * 3)

print()


# Membership Operator (in)
language = "Python Programming"

print("Membership (in):")
print("Python" in language)
print("Java" in language)

print()


# Membership Operator (not in)
print("Membership (not in):")
print("Java" not in language)
print("Python" not in language)

print()


# String Comparison
str1 = "Apple"
str2 = "Banana"

print("Comparison:")
print("str1 == str2 :", str1 == str2)
print("str1 != str2 :", str1 != str2)
print("str1 < str2  :", str1 < str2)
print("str1 > str2  :", str1 > str2)

print()


