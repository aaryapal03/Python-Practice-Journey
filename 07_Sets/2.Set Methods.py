
# Original Set
numbers = {10, 20, 30, 40, 50}
print(numbers)

print()

# add()
numbers.add(60)
print(numbers)

print()

# update()
numbers.update([70, 80])
print(numbers)

print()

# remove()
numbers.remove(20)
print(numbers)

print()

# discard()
numbers.discard(100)
print(numbers)

print()

# pop()
removed_element = numbers.pop()
print(numbers)

print()

# copy()
new_set = numbers.copy()
print(new_set)

print()

# clear()
sample = {1, 2, 3}
sample.clear()
print(sample)

print()

# Built-in Functions

values = {15, 5, 30, 20, 10}

print("Built-in Functions")
print("Length :", len(values))
print("Minimum :", min(values))
print("Maximum :", max(values))
print("Sum :", sum(values))
print("Sorted :", sorted(values))

print()

