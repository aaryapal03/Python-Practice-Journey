
# Creating a Set
fruits = {"Apple", "Banana", "Mango", "Orange"}
print(fruits)

print()

# Duplicate Values are Removed Automatically
numbers = {10, 20, 30, 20, 10, 40, 50}
print(numbers)

print()

# Mixed Data Types
mixed_set = {"Aarya", 19, 89.5, True}
print(mixed_set)

print()

# Empty Set
empty_set = set()
print(empty_set)

print()

# Type of Set

print("Type:", type(fruits))

print()


# Iterating Through a Set
print("Elements of the Set:")

for i in fruits:
    print(i)

print()

#End of Program
