
# Creating a Dictionary
student = {"name": "Aarya", "age": 19, "course": "Data Science","city": "Mumbai"}
print(student)

print()

# Accessing Values

print("Name :", student["name"])
print("Age :", student["age"])
print("Course :", student["course"])

print()

# Using get()
print("City :", student.get("city"))

print()


# Dictionary with Different Data Types
employee = {"id": 101,"name": "Rahul", "salary": 50000, "is_employee": True}
print(employee)

print()

# Empty Dictionary
empty_dict = {}
print(empty_dict)

print()


# Type of Dictionary
print("Type:", type(student))

print()


